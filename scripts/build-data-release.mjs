import { createHash } from 'node:crypto';
import { copyFile, mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const [dictionaryFolder = 'dict', outputFolder = 'release-data', outputSource = 'src/dataAssets.ts'] = process.argv.slice(2);
const dataTag = process.env.CUSTOM_FURIGANA_DATA_TAG ?? 'data-4.0.0';

const desktopFiles = [
	'jmdict-eng-3.6.2.json.gz',
	'wiktionary-ja-ko-2026-10-01.json.gz',
	'base.dat.gz',
	'cc.dat.gz',
	'check.dat.gz',
	'tid.dat.gz',
	'tid_map.dat.gz',
	'tid_pos.dat.gz',
	'unk.dat.gz',
	'unk_char.dat.gz',
	'unk_compat.dat.gz',
	'unk_invoke.dat.gz',
	'unk_map.dat.gz',
	'unk_pos.dat.gz',
];

async function shardFiles(folder, prefix) {
	return (await readdir(path.join(dictionaryFolder, folder)))
		.filter((name) => name.startsWith(prefix) && name.endsWith('.json.gz'))
		.sort()
		.map((name) => `${folder}/${name}`);
}

const files = [
	...desktopFiles,
	...(await shardFiles('mobile', 'jmdict-')),
	...(await shardFiles('auto', 'auto-')),
];

await mkdir(outputFolder, { recursive: true });
const records = {};
for (const relativePath of files) {
	const input = path.join(dictionaryFolder, relativePath);
	const contents = await readFile(input);
	const asset = `data-${relativePath.replaceAll('/', '--')}`;
	records[relativePath] = {
		asset,
		sha256: createHash('sha256').update(contents).digest('hex'),
	};
	await copyFile(input, path.join(outputFolder, asset));
}

const source = `// Generated by scripts/build-data-release.mjs. Do not edit manually.\n\n` +
	`export const DATA_RELEASE_TAG = ${JSON.stringify(dataTag)};\n\n` +
	`export interface DataAsset {\n\tasset: string;\n\tsha256: string;\n}\n\n` +
	`export const DATA_ASSETS: Record<string, DataAsset> = ${JSON.stringify(records, null, '\t')};\n`;

await writeFile(outputSource, source);
console.log(`Prepared ${files.length} data assets for ${dataTag}.`);
